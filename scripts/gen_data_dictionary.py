"""Generate docs/database/data-dictionary.md from the SQLAlchemy models (single source of truth)."""

from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ.setdefault("DATABASE_URL", "postgresql://x:y@localhost/z")
os.environ.setdefault("AUTH_PROVIDER", "local")
os.environ.setdefault("LOCAL_JWT_SECRET", "x" * 40)

import app.db.models  # noqa: E402,F401
from app.db.base import Base  # noqa: E402


def main() -> int:
    out = [
        "# Data dictionary (generated)",
        "",
        "Generated by `scripts/gen_data_dictionary.py` from the SQLAlchemy models - do not edit by hand.",
        "All tables live in schema `dms`, have row-level security enabled (deny-all for API roles) and are",
        "reachable only through the backend. See `docs/database/erd.md` for relationships and",
        "`docs/security/tenant-isolation.md` for the tenancy rules.",
        "",
    ]
    tables = sorted(Base.metadata.tables.values(), key=lambda t: t.name)
    out.append(f"{len(tables)} tables.\n")
    for t in tables:
        out.append(f"## `{t.name}`\n")
        tenant = "organization_id" in t.columns
        out.append(f"Tenant-scoped: **{'yes' if tenant else 'no (global)'}**\n")
        out.append("| column | type | null | default | notes |")
        out.append("|---|---|---|---|---|")
        fks = {
            c.name: [f"{fk.column.table.name}.{fk.column.name}" for fk in c.foreign_keys]
            for c in t.columns
        }
        for c in t.columns:
            notes = []
            if c.primary_key:
                notes.append("PK")
            if fks[c.name]:
                notes.append("FK -> " + ", ".join(fks[c.name]))
            if c.computed is not None:
                notes.append("generated")
            default = ""
            if c.server_default is not None:
                default = str(getattr(c.server_default, "arg", c.server_default))[:40]
            out.append(
                f"| `{c.name}` | {str(c.type)[:40]} | {'yes' if c.nullable else 'no'} | {default} | {'; '.join(notes)} |"
            )
        extras = []
        for con in t.constraints:
            cls = type(con).__name__
            if cls == "CheckConstraint":
                extras.append(f"check `{con.name}`: `{str(con.sqltext)[:110]}`")
            elif cls == "UniqueConstraint":
                extras.append(f"unique `{con.name}` ({', '.join(c.name for c in con.columns)})")
            elif cls == "ForeignKeyConstraint" and len(con.columns) > 1:
                extras.append(
                    f"composite FK `{con.name}` ({', '.join(c.name for c in con.columns)}) - tenant-consistent"
                )
        for ix in sorted(t.indexes, key=lambda i: i.name or ""):
            where = ix.dialect_options["postgresql"].get("where")
            extras.append(
                f"{'unique ' if ix.unique else ''}index `{ix.name}`"
                + (f" where `{where}`" if where is not None else "")
            )
        if extras:
            out.append("")
            out.append("Constraints and indexes:\n")
            out.extend(f"- {e}" for e in extras)
        out.append("")
    target = ROOT / "docs" / "database" / "data-dictionary.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {target} ({len(tables)} tables)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
