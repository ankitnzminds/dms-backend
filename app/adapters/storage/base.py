"""Provider-independent object storage interface (see ADR-0005).

Business logic only sees ``StorageProvider``. Object keys are opaque, generated by the DMS
(never derived from user filenames) and stored in ``document_versions`` together with the
storage location id, so migrating providers is an explicit copy/verify/cutover operation.
"""

from __future__ import annotations

import uuid
from collections.abc import Iterator
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import BinaryIO, Protocol


class StorageError(Exception):
    """Generic storage failure (network, permission, unexpected response)."""


class ObjectNotFoundError(StorageError):
    pass


@dataclass(frozen=True)
class ObjectMeta:
    size: int
    content_type: str | None = None


@dataclass(frozen=True)
class StorageCapabilities:
    temporary_download_urls: bool = False
    multipart_upload: bool = False
    server_side_copy: bool = True
    native_checksum: bool = False


class StorageProvider(Protocol):
    name: str
    capabilities: StorageCapabilities

    def put_object(
        self, bucket: str, key: str, data: BinaryIO, size: int, content_type: str
    ) -> None:
        """Store exactly ``size`` bytes. Must fail if the key already exists (no overwrite)."""

    def stream_object(
        self, bucket: str, key: str, chunk_size: int = 1024 * 1024
    ) -> Iterator[bytes]:
        """Yield the object's bytes. Raises ObjectNotFoundError if missing."""

    def head_object(self, bucket: str, key: str) -> ObjectMeta | None: ...

    def copy_object(self, bucket: str, source_key: str, destination_key: str) -> None: ...

    def delete_object(self, bucket: str, key: str) -> None:
        """Idempotent: deleting a missing object is not an error."""

    def health_check(self, bucket: str) -> bool: ...


def new_object_key(organization_id: uuid.UUID) -> str:
    """Opaque key: tenant prefix + date shard + random id. Never contains user input."""
    now = datetime.now(UTC)
    return f"{organization_id}/{now:%Y/%m}/{uuid.uuid4().hex}"
